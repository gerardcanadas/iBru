// P3, P50, P97 at months 0–60 for boys and girls.

struct PercentilePoint: Identifiable {
    var id: Double { ageMonths }
    let ageMonths: Double
    let p3: Double
    let p50: Double
    let p97: Double
}

enum WHOGrowthData {

    static func weightPoints(sex: BabySex) -> [PercentilePoint] {
        zip3(sex == .male ? boysWeightP3 : girlsWeightP3,
             sex == .male ? boysWeightP50 : girlsWeightP50,
             sex == .male ? boysWeightP97 : girlsWeightP97)
    }

    static func heightPoints(sex: BabySex) -> [PercentilePoint] {
        zip3(sex == .male ? boysHeightP3 : girlsHeightP3,
             sex == .male ? boysHeightP50 : girlsHeightP50,
             sex == .male ? boysHeightP97 : girlsHeightP97)
    }

    static func headPoints(sex: BabySex) -> [PercentilePoint] {
        zip3(sex == .male ? boysHeadP3 : girlsHeadP3,
             sex == .male ? boysHeadP50 : girlsHeadP50,
             sex == .male ? boysHeadP97 : girlsHeadP97)
    }

    /// Returns an interpolated PercentilePoint for the given age, or nil if out of range.
    static func interpolated(ageMonths: Double, from table: [PercentilePoint]) -> PercentilePoint? {
        guard !table.isEmpty else { return nil }
        if ageMonths <= table[0].ageMonths { return table[0] }
        if ageMonths >= table[table.count - 1].ageMonths { return nil }
        for i in 0 ..< table.count - 1 {
            let lo = table[i]; let hi = table[i + 1]
            guard ageMonths < hi.ageMonths else { continue }
            let t = (ageMonths - lo.ageMonths) / (hi.ageMonths - lo.ageMonths)
            return PercentilePoint(
                ageMonths: ageMonths,
                p3:  lo.p3  + t * (hi.p3  - lo.p3),
                p50: lo.p50 + t * (hi.p50 - lo.p50),
                p97: lo.p97 + t * (hi.p97 - lo.p97)
            )
        }
        return table.last
    }

    private static func zip3(_ p3: [Double], _ p50: [Double], _ p97: [Double]) -> [PercentilePoint] {
        precondition(p3.count == p50.count && p50.count == p97.count)
        return p3.indices.map { i in
            PercentilePoint(ageMonths: Double(i), p3: p3[i], p50: p50[i], p97: p97[i])
        }
    }

